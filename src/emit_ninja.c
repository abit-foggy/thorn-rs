/* emit_ninja.c - standalone build.ninja fragment emitter.
 *
 * Emits the exact rule/build shape from docs/SCOPING.md section 3.4:
 * a dedicated `rule rustc` with per-edge variables, wired into ninja's
 * native depfile protocol (depfile = $out.d, deps = gcc) - the same
 * convention thorn's rule cc uses, so the fragment composes with any
 * thorn-generated build.ninja. */
#include <string.h>

#include "include/emit.h"
#include "include/plan.h"

static const char *base_name(const char *p)
{
    const char *b = strrchr(p, '/');
    return b ? b + 1 : p;
}

static int validate_paths(const RustCrate *c)
{
    struct {
        const char *path;
        const char *what;
    } checks[] = {
        { c->frag,    "fragment path"   },
        { c->out,     "artifact path"   },
        { c->root,    "crate root path" },
    };
    for (size_t i = 0; i < sizeof(checks) / sizeof(checks[0]); i++) {
        if (!path_safe(checks[i].path)) {
            diag("%s contains characters that are unsafe in build "
                 "fragments: '%s'", checks[i].what, checks[i].path);
            return THORN_RS_EXIT_SCAN;
        }
    }
    return 0;
}

int emit_ninja(const RustCrate *c, const char *tool, FILE *out)
{
    int rc = validate_paths(c);
    if (rc)
        return rc;

    char flags[2048];
    if (plan_rustflags(c, flags, sizeof(flags))) {
        diag("cannot plan rustc flags for crate '%s'", c->name);
        return THORN_RS_EXIT_SCAN;
    }

    fprintf(out, "# %s - generated by thorn-rs %s, do not edit\n",
            base_name(c->frag), THORN_RS_VERSION);
    fprintf(out, "# crate: %s (deterministic: same inputs, same bytes)\n\n",
            c->name);
    fprintf(out, "ninja_required_version = 1.3\n");
    fprintf(out, "rustc = %s\n\n", tool);

    fprintf(out, "rule rustc\n");
    fprintf(out, "  command = $rustc --edition $edition --crate-name "
                 "$crate_name --crate-type staticlib $rustflags "
                 "--emit=dep-info=$out.d,link=$out $in\n");
    fprintf(out, "  depfile = $out.d\n");
    fprintf(out, "  deps = gcc\n");
    fprintf(out, "  description = rustc $crate_name -> $out\n\n");

    fprintf(out, "build %s: rustc %s\n", c->out, c->root);
    fprintf(out, "  crate_name = %s\n", c->name);
    fprintf(out, "  edition = %s\n", c->edition);
    fprintf(out, "  rustflags =%s\n", flags);
    return 0;
}
