/* emit_make.c - POSIX/GNU Make fragment emitter.
 *
 * Emits the exact snippet shape from the Phase 0 contract: a single
 * explicit rule per crate, GCC-style depfile inclusion via -include
 * (silently ignored on the first build), and RUSTC ?= so the RUSTC
 * environment variable flows through without thorn-rs ever reading it.
 * Recipe lines use real tabs and $@/$< automatics; the rustc argv is
 * identical to the ninja fragment's command expansion. */
#include <string.h>

#include "include/emit.h"
#include "include/plan.h"

static const char *base_name(const char *p)
{
    const char *b = strrchr(p, '/');
    return b ? b + 1 : p;
}

static int validate_paths(const RustCrate *c)
{
    struct {
        const char *path;
        const char *what;
    } checks[] = {
        { c->frag,    "fragment path"   },
        { c->out,     "artifact path"   },
        { c->root,    "crate root path" },
    };
    for (size_t i = 0; i < sizeof(checks) / sizeof(checks[0]); i++) {
        if (!path_safe(checks[i].path)) {
            diag("%s contains characters that are unsafe in build "
                 "fragments: '%s'", checks[i].what, checks[i].path);
            return THORN_RS_EXIT_SCAN;
        }
    }
    return 0;
}

int emit_make(const RustCrate *c, const char *tool, FILE *out)
{
    int rc = validate_paths(c);
    if (rc)
        return rc;

    char flags[2048];
    if (plan_rustflags(c, flags, sizeof(flags))) {
        diag("cannot plan rustc flags for crate '%s'", c->name);
        return THORN_RS_EXIT_SCAN;
    }

    fprintf(out, "# %s - generated by thorn-rs %s, do not edit\n",
            base_name(c->frag), THORN_RS_VERSION);
    fprintf(out, "# crate: %s (deterministic: same inputs, same bytes)\n",
            c->name);
    fprintf(out, "RUSTC ?= %s\n\n", tool);

    fprintf(out, "%s: %s\n", c->out, c->root);
    fprintf(out, "\t$(RUSTC) --edition %s --crate-name %s "
                 "--crate-type staticlib%s "
                 "--emit=dep-info=$@.d,link=$@ $<\n\n",
            c->edition, c->name, flags);

    fprintf(out, "-include %s.d\n", c->out);
    return 0;
}
