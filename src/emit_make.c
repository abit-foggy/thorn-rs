/*
 * emit_make.c - POSIX/GNU Make fragment emitter.
 *
 * RUSTC ?= lets the RUSTC environment flow through without thorn-rs
 * reading it; -include pulls in the depfile once rustc has written it.
 * When the fragment sits in a subdirectory, RS_ROOT anchors every path
 * back to the emission working directory so `make -C <out-dir>` works
 * from anywhere; fragments in the working directory keep plain
 * relative paths.
 *
 * Part of thorn-rs, the zero-cargo Rust staticlib companion for thorn.
 * Copyright (c) 2026 abit-foggy
 * SPDX-License-Identifier: BSD-2-Clause
 */

#include <string.h>

#include "include/emit.h"
#include "include/plan.h"
#include "include/verify.h"

static const char *
base_name(const char *p)
{
    const char *b = strrchr(p, '/');
    return b ? b + 1 : p;
}

static int
validate_paths(const RustCrate *c)
{
    struct {
        const char *path;
        const char *what;
    } checks[] = {
        { c->frag, "fragment path"   },
        { c->out,  "artifact path"   },
        { c->root, "crate root path" },
    };
    for (size_t i = 0; i < sizeof(checks) / sizeof(checks[0]); i++) {
        if (!path_safe(checks[i].path)) {
            diag("%s contains characters that are unsafe in build "
                 "fragments: '%s'", checks[i].what, checks[i].path);
            return THORN_RS_EXIT_SCAN;
        }
    }
    return 0;
}

/* Prefix a path with RS_ROOT when the fragment sits in a subdir.
   Returns NULL when the result would not fit (callers pre-validate
   paths, so this is a hard-error signal). */
static const char *
rp(char *buf, size_t n, const char *ups, const char *path)
{
    size_t pl = strlen(path);

    if (ups == NULL || *ups == '\0') {
        if (pl >= n)
            return NULL;
        memcpy(buf, path, pl + 1);
        return buf;
    }
    if (pl + 11 >= n)
        return NULL;
    memcpy(buf, "$(RS_ROOT)/", 11);
    memcpy(buf + 11, path, pl + 1);
    return buf;
}

static int
overflow(void)
{
    diag("prefixed path exceeds the fragment buffer");
    return THORN_RS_EXIT_SCAN;
}

int
emit_make_set(const RustCrate *const *crates, size_t count,
              const char *tool, const char *ups, FILE *out)
{
    if (count == 0)
        return 0;

    char stamps[64][512];
    if (count > 64) {
        diag("at most 64 crates per fragment");
        return THORN_RS_EXIT_SCAN;
    }

    int any_verify = 0;
    for (size_t i = 0; i < count; i++)
        if (crates[i]->header[0])
            any_verify = 1;

    fprintf(out, "# %s - generated by thorn-rs %s, do not edit\n",
            base_name(crates[0]->frag), THORN_RS_VERSION);
    fprintf(out, "# %zu crate%s (deterministic: same inputs, same "
                 "bytes)\n", count, count == 1 ? "" : "s");
    fprintf(out, "RUSTC ?= %s\n", tool);
    if (any_verify)
        fprintf(out, "THORN_RS ?= thorn-rs\n");
    if (ups && *ups)
        fprintf(out, "RS_ROOT := $(abspath $(dir $(lastword "
                     "$(MAKEFILE_LIST)))%s)\n", ups);
    fprintf(out, "\n");

    if (count > 1 || any_verify) {
        fprintf(out, ".PHONY: all\nall:");
        for (size_t i = 0; i < count; i++) {
            char b1[1200], b2[1200];
            const char *p1 = rp(b1, sizeof(b1), ups, crates[i]->out);
            if (p1 == NULL)
                return overflow();
            fprintf(out, " %s", p1);
            if (crates[i]->header[0]) {
                snprintf(stamps[i], sizeof(stamps[i]),
                         ".thorn-rs/%s.verified", crates[i]->name);
                const char *p2 = rp(b2, sizeof(b2), ups, stamps[i]);
                if (p2 == NULL)
                    return overflow();
                fprintf(out, " %s", p2);
            } else {
                stamps[i][0] = '\0';
            }
        }
        fprintf(out, "\n\n");
    }

    for (size_t i = 0; i < count; i++) {
        const RustCrate *c = crates[i];

        int rc = validate_paths(c);
        if (rc)
            return rc;

        char flags[2048];
        if (plan_rustflags(c, flags, sizeof(flags))) {
            diag("cannot plan rustc flags for crate '%s'", c->name);
            return THORN_RS_EXIT_SCAN;
        }

        char o1[1200], r1[1200];
        const char *po = rp(o1, sizeof(o1), ups, c->out);
        const char *pr = rp(r1, sizeof(r1), ups, c->root);
        if (po == NULL || pr == NULL)
            return overflow();
        fprintf(out, "%s: %s\n", po, pr);
        fprintf(out, "\t$(RUSTC) --edition %s --crate-name %s "
                     "--crate-type staticlib%s "
                     "--emit=dep-info=$@.d,link=$@ $<\n\n",
                c->edition, c->name, flags);

        if (c->header[0]) {
            char vcmd[4096];
            if (verify_command(c->out, c->header, &c->capi_syms, vcmd,
                               sizeof(vcmd))) {
                diag("cannot plan the verification command for crate "
                     "'%s'", c->name);
                return THORN_RS_EXIT_SCAN;
            }
            char o2[1200], r2[1200], h2[1200], s2[1200];
            snprintf(stamps[i], sizeof(stamps[i]),
                     ".thorn-rs/%s.verified", c->name);
            const char *ps = rp(s2, sizeof(s2), ups, stamps[i]);
            const char *p2o = rp(o2, sizeof(o2), ups, c->out);
            const char *p2r = rp(r2, sizeof(r2), ups, c->header);
            const char *p2h = rp(h2, sizeof(h2), ups, ".thorn-rs");
            if (ps == NULL || p2o == NULL || p2r == NULL || p2h == NULL)
                return overflow();
            fprintf(out, "%s: %s %s\n", ps, p2o, p2r);
            fprintf(out, "\tmkdir -p %s && $(THORN_RS) %s && touch $@\n\n",
                    p2h, vcmd);
        }
    }

    for (size_t i = 0; i < count; i++) {
        char b1[1200];
        const char *pi = rp(b1, sizeof(b1), ups, crates[i]->out);
        if (pi == NULL)
            return overflow();
        fprintf(out, "-include %s.d\n", pi);
    }
    return 0;
}
